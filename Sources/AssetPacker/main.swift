import Foundation

// Usage: AssetPacker <assets directory> <output .swift file>
// Writes every regular file under the directory as a base64 string keyed by its relative path.

let arguments = CommandLine.arguments
guard arguments.count == 3 else {
    FileHandle.standardError.write(Data("usage: AssetPacker <assets dir> <output file>\n".utf8))
    exit(EXIT_FAILURE)
}

let root = URL(filePath: arguments[1], directoryHint: .isDirectory).standardizedFileURL
let output = URL(filePath: arguments[2])
let ignoredNames: Set<String> = [".DS_Store"]

let enumerator = FileManager.default.enumerator(
    at: root,
    includingPropertiesForKeys: [.isRegularFileKey]
)
var entries: [(path: String, base64: String)] = []
for case let file as URL in enumerator ?? NSEnumerator() {
    guard try file.resourceValues(forKeys: [.isRegularFileKey]).isRegularFile == true,
        !ignoredNames.contains(file.lastPathComponent)
    else { continue }
    let relativePath = String(
        file.standardizedFileURL.path(percentEncoded: false).dropFirst(
            root.path(percentEncoded: false).count))
    entries.append((relativePath, try Data(contentsOf: file).base64EncodedString()))
}
entries.sort { $0.path < $1.path }

var source = "// Generated by AssetPacker from Assets/. Do not edit.\n"
source += "enum GeneratedAssets {\n    static let base64ByPath: [String: String] = [\n"
for entry in entries {
    source += "        \"\(entry.path)\": \"\(entry.base64)\",\n"
}
source += "    ]\n}\n"
try source.write(to: output, atomically: true, encoding: .utf8)
